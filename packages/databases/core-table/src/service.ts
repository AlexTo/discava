// Course, Module, Lesson, and ContentItem join the `curriculum` collection
// (declared on each entity's primary index), so a course's full curriculum
// can be read with a single query: coreTableService.collections.curriculum({
// courseId }).go(). Other entities are included for a single access point
// but don't need to be queried alongside the curriculum. The analytics
// aggregates share the `analytics` collection (one pk per course); markers
// have their own pk, as they are never read, only written.
export const createCoreTableService = async () => {
  const [
    user,
    course,
    lesson,
    module,
    contentItem,
    enrolment,
    courseInstructor,
    coursePreview,
    assignmentSubmission,
    progress,
    quizAttempt,
    quizSummary,
    itemCompletion,
    certificate,
    videoPosition,
    courseStats,
    periodStats,
    lessonStats,
    quizQuestionStats,
    quizScoreStats,
    analyticsMarker,
    notification,
    notificationState,
    notificationPreference,
    notificationBroadcast,
    announcement,
    category,
    categoryClaim,
    discussionPost,
    discussionVote,

    review,
    courseRating,
    instructorProfile,
    profileHandleClaim,
    coupon,
    couponRedemption,
  ] = await Promise.all([
    createUserEntity(),
    createCourseEntity(),
    createLessonEntity(),
    createModuleEntity(),
    createContentItemEntity(),
    createEnrolmentEntity(),
    createCourseInstructorEntity(),
    createCoursePreviewEntity(),
    createAssignmentSubmissionEntity(),
    createProgressEntity(),
    createQuizAttemptEntity(),
    createQuizSummaryEntity(),
    createItemCompletionEntity(),
    createCertificateEntity(),
    createVideoPositionEntity(),
    createCourseStatsEntity(),
    createPeriodStatsEntity(),
    createLessonStatsEntity(),
    createQuizQuestionStatsEntity(),
    createQuizScoreStatsEntity(),
    createAnalyticsMarkerEntity(),
    createNotificationEntity(),
    createNotificationStateEntity(),
    createNotificationPreferenceEntity(),
    createNotificationBroadcastEntity(),
    createAnnouncementEntity(),
    createCategoryEntity(),
    createCategoryClaimEntity(),
    createDiscussionPostEntity(),
    createDiscussionVoteEntity(),

    createReviewEntity(),
    createCourseRatingEntity(),
    createInstructorProfileEntity(),
    createProfileHandleClaimEntity(),
    createCouponEntity(),
    createCouponRedemptionEntity(),
  ]);

  return new Service({
    user,
    course,
    module,
    lesson,
    contentItem,
    enrolment,
    courseInstructor,
    coursePreview,
    assignmentSubmission,
    progress,
    quizAttempt,
    quizSummary,
    itemCompletion,
    certificate,
    videoPosition,
    courseStats,
    periodStats,
    lessonStats,
    quizQuestionStats,
    quizScoreStats,
    analyticsMarker,
    notification,
    notificationState,
    notificationPreference,
    notificationBroadcast,
    announcement,
    category,
    categoryClaim,
    discussionPost,
    discussionVote,

    review,
    courseRating,
    instructorProfile,
    profileHandleClaim,
    coupon,
    couponRedemption,
  });
};

export type CoreTable = Awaited<ReturnType<typeof createCoreTableService>>;
