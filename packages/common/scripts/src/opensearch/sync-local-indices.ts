import { loadManifest, syncIndices } from '@discava/search';
import { Client } from '@opensearch-project/opensearch';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';

const { port } = JSON.parse(readFileSync('config.json', 'utf-8')).localDev;

// No SigV4 signing locally: the local container's security plugin is
// disabled (start-container.ts), unlike the deployed Serverless collection.
const client = new Client({ node: `http://127.0.0.1:${port}` });

// The same manifest CDK's index-sync custom resource reads, generated by
// `nx run @discava/search:generate-indices-manifest` (a dependency of this
// project's `dev` target), so local dev and deployed stages never see
// different indices.
const manifestPath = fileURLToPath(
  new URL(
    '../../../../../dist/packages/databases/search/indices/indices.json',
    import.meta.url,
  ),
);

// A cold JVM start (security, ML and performance-analyzer plugins all
// loading) can take well over 30s under a contended CI runner (#267), so
// this allows a couple of minutes rather than giving up right as it's
// still coming up.
const HEALTH_CHECK_ATTEMPTS = 90;
const HEALTH_CHECK_RETRY_DELAY_MS = 2_000;

for (let attempt = 1; ; attempt++) {
  try {
    await client.cluster.health({});
    break;
  } catch (error) {
    if (attempt >= HEALTH_CHECK_ATTEMPTS) {
      console.error(
        `Local OpenSearch at 127.0.0.1:${port} wasn't healthy after ${attempt} attempts:`,
        error,
      );
      throw error;
    }
    await new Promise((resolve) =>
      setTimeout(resolve, HEALTH_CHECK_RETRY_DELAY_MS),
    );
  }
}

await syncIndices(client, loadManifest(manifestPath));
console.log('Local OpenSearch indices are in sync.');
