import { Code } from 'aws-cdk-lib/aws-lambda';
import { Construct } from 'constructs';
import { readFileSync } from 'fs';
import { join } from 'path';
import { fileURLToPath } from 'url';
import {
  OpenSearchCollection,
  OpenSearchCollectionProps,
} from '../../core/opensearch.js';
import { findWorkspaceRoot } from '../../core/workspace.js';

const workspaceRoot = findWorkspaceRoot(
  fileURLToPath(new URL(import.meta.url)),
);

const { runtimeConfigKey } = JSON.parse(
  readFileSync(
    join(workspaceRoot, 'packages/databases/search/config.json'),
    'utf-8',
  ),
) as { runtimeConfigKey: string };

// Generated by `nx run @discava/search:indices`; see
// generate-indices-manifest.ts. A build-time artifact, not checked in, so
// this (and every CDK synth) must run after that target.
const manifest = JSON.parse(
  readFileSync(
    join(workspaceRoot, 'dist/packages/databases/search/indices/indices.json'),
    'utf-8',
  ),
) as {
  indices: {
    name: string;
    settings?: Record<string, unknown>;
    mappings: Record<string, unknown>;
  }[];
  hash: string;
};

export type SearchCollectionProps = Omit<
  OpenSearchCollectionProps,
  | 'runtimeConfigKey'
  | 'indices'
  | 'manifestHash'
  | 'indexSyncHandlerCode'
  | 'collectionName'
> & {
  /** @default 'discava-search' */
  readonly collectionName?: string;
};

/** Discava's search collection: courses (#53), for now. */
export class SearchCollection extends OpenSearchCollection {
  constructor(
    scope: Construct,
    id: string,
    { collectionName = 'discava-search', ...props }: SearchCollectionProps = {},
  ) {
    super(scope, id, {
      ...props,
      collectionName,
      runtimeConfigKey,
      indices: manifest.indices,
      manifestHash: manifest.hash,
      indexSyncHandlerCode: Code.fromAsset(
        fileURLToPath(
          new URL(
            '../../../../../../dist/packages/databases/search/bundle/lambda/index-sync',
            import.meta.url,
          ),
        ),
      ),
    });
  }
}
