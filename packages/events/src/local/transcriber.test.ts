import { beforeEach, describe, expect, it, vi } from 'vitest';
import { createTranscriber, PLACEHOLDER_VTT } from './transcriber.js';

const { send } = vi.hoisted(() => ({ send: vi.fn() }));

vi.mock('@aws-sdk/client-s3', () => ({
  PutObjectCommand: vi.fn(function (input) {
    return { type: 'put', ...input };
  }),
}));

const REQUEST = {
  jobName: 'captions-item-1-nonce-1',
  tags: {
    courseId: 'course-1',
    moduleId: 'module-1',
    lessonId: 'lesson-1',
    contentItemId: 'item-1',
    nonce: 'nonce-1',
  },
  outputBucket: 'media',
  outputKey: 'courses/x/content-items/item-1/transcribe-output/nonce-1/',
};

const build = () => {
  const onFinished = vi.fn(async () => {});
  const transcriber = createTranscriber({
    s3: { send } as never,
    onFinished,
    log: () => {},
  });
  return { transcriber, onFinished };
};

beforeEach(() => {
  vi.clearAllMocks();
  send.mockResolvedValue({});
});

describe('PLACEHOLDER_VTT', () => {
  it('is a WebVTT file with the one placeholder cue', () => {
    expect(PLACEHOLDER_VTT.startsWith('WEBVTT\n')).toBe(true);
    expect(PLACEHOLDER_VTT).toContain('-->');
    expect(PLACEHOLDER_VTT).toContain(
      'Captions are generated by Amazon Transcribe when deployed.',
    );
  });
});

describe('createTranscriber', () => {
  it('writes the placeholder where Transcribe writes its VTT, then reports COMPLETED', async () => {
    const { transcriber, onFinished } = build();

    transcriber.submit(REQUEST);
    await transcriber.idle();

    expect(send).toHaveBeenCalledWith({
      type: 'put',
      Bucket: 'media',
      Key: `${REQUEST.outputKey}${REQUEST.jobName}.vtt`,
      Body: PLACEHOLDER_VTT,
      ContentType: 'text/vtt',
    });
    expect(onFinished).toHaveBeenCalledWith({
      jobName: REQUEST.jobName,
      status: 'COMPLETED',
      ...REQUEST.tags,
      vttKey: `${REQUEST.outputKey}${REQUEST.jobName}.vtt`,
    });
    expect(send.mock.invocationCallOrder[0]).toBeLessThan(
      onFinished.mock.invocationCallOrder[0],
    );
  });

  it('answers straight away, finishing in the background', () => {
    const { transcriber, onFinished } = build();

    transcriber.submit(REQUEST);

    expect(onFinished).not.toHaveBeenCalled();
  });

  it('reports FAILED when the placeholder cannot be written', async () => {
    send.mockRejectedValue(new Error('S3Mock is down'));
    const { transcriber, onFinished } = build();

    transcriber.submit(REQUEST);
    await transcriber.idle();

    expect(onFinished).toHaveBeenCalledWith(
      expect.objectContaining({ status: 'FAILED' }),
    );
  });

  it('refuses a job without the tags the handler needs', () => {
    const { transcriber } = build();

    expect(() =>
      transcriber.submit({ ...REQUEST, tags: { courseId: 'course-1' } }),
    ).toThrow('tags');
  });

  it('survives its completion handler failing', async () => {
    const { transcriber, onFinished } = build();
    onFinished.mockRejectedValue(new Error('boom'));

    transcriber.submit(REQUEST);

    await expect(transcriber.idle()).resolves.toBeUndefined();
  });
});
