import { PutObjectCommand, type S3Client } from '@aws-sdk/client-s3';
import type { LocalTranscriptionJobRequest } from '@discava/common-server-utils/local-dev';
import type { TranscribeOutcome } from '../media/transcribe-outcome.js';

// Local dev's stand-in for Transcribe (#137): no speech model, just a
// placeholder WebVTT written where Transcribe writes its own, so everything
// after recognition (the copy into the version's folder, the default track,
// the player's captions menu) runs for real.

/** The one cue every local job produces. */
export const PLACEHOLDER_VTT = `WEBVTT

00:00:00.000 --> 00:00:30.000
Captions are generated by Amazon Transcribe when deployed.
`;

export interface TranscriberOptions {
  s3: S3Client;
  /** Called once a job finishes, as Transcribe's completion event would. */
  onFinished: (outcome: TranscribeOutcome) => Promise<void>;
  log: (message: string) => void;
}

/**
 * Transcribe's part, locally: `submit` accepts a job and returns at once, as
 * StartTranscriptionJob does; in the background the placeholder is written to
 * `<outputKey><jobName>.vtt` (the scratch folder) and the outcome reported,
 * COMPLETED, or FAILED if the write fails.
 */
export const createTranscriber = ({
  s3,
  onFinished,
  log,
}: TranscriberOptions) => {
  let idle: Promise<void> = Promise.resolve();

  const run = async (
    request: LocalTranscriptionJobRequest,
    target: Omit<TranscribeOutcome, 'jobName' | 'status' | 'vttKey'>,
  ) => {
    const { jobName, outputBucket, outputKey } = request;
    const vttKey = `${outputKey}${jobName}.vtt`;
    let status: 'COMPLETED' | 'FAILED' = 'COMPLETED';
    try {
      await s3.send(
        new PutObjectCommand({
          Bucket: outputBucket,
          Key: vttKey,
          Body: PLACEHOLDER_VTT,
          ContentType: 'text/vtt',
        }),
      );
    } catch (error) {
      log(
        `${jobName}: couldn't write the placeholder: ${(error as Error).message}`,
      );
      status = 'FAILED';
    }
    log(`${jobName} ${status}`);
    try {
      await onFinished({
        jobName,
        status,
        ...target,
        vttKey: status === 'COMPLETED' ? vttKey : undefined,
      });
    } catch (error) {
      log(
        `${jobName}: its outcome failed; not retried locally: ${(error as Error).message}`,
      );
    }
  };

  return {
    /** Accepts a job, as StartTranscriptionJob does. */
    submit(request: LocalTranscriptionJobRequest): void {
      const { courseId, moduleId, lessonId, contentItemId, nonce } =
        request.tags;
      if (!courseId || !moduleId || !lessonId || !contentItemId || !nonce) {
        throw new Error(
          'The job needs courseId, moduleId, lessonId, contentItemId and nonce tags',
        );
      }
      idle = idle.then(() =>
        run(request, { courseId, moduleId, lessonId, contentItemId, nonce }),
      );
    },
    /** Resolves once every accepted job has finished (for tests). */
    idle: () => idle,
  };
};
